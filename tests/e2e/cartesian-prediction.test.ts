// Observe before acting, including synchronous React changes. Deadlines are failure
// bounds, not scheduling delays; every successful wait is driven by DOM mutations.
async function state(page: Page, predicate: string, action = "") {
  await page.evaluate(`new Promise((resolve,reject)=>{
    const observer=new MutationObserver(check);
    const timer=setTimeout(()=>{observer.disconnect();reject(Error(
      ${JSON.stringify(predicate)}+"\\n"+document.querySelector('.prediction-workspace')?.outerHTML
    ))},8000);
    function check(){if(${predicate}){observer.disconnect();clearTimeout(timer);resolve(true)}}
    observer.observe(document.body,{subtree:true,childList:true,attributes:true,characterData:true});
    ${action};check();
  })`);
}
function click(selector: string) {
  return `document.querySelector(${JSON.stringify(selector)}).click()`;
}
async function select(page: Page, selector: string, value: string) {
  await page.evaluate(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});
    e.value=${JSON.stringify(value)};e.dispatchEvent(new Event('change',{bubbles:true}));return true})()`);
}
async function input(page: Page, selector: string, value: string) {
  await page.evaluate(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});
    Object.getOwnPropertyDescriptor(HTMLInputElement.prototype,'value').set.call(e,${JSON.stringify(value)});
    e.dispatchEvent(new Event('input',{bubbles:true}));return true})()`);
}
async function exported(page: Page) {
  // Capture the real download Blob, without replacing conversion or Worker behavior.
  const value = await page.evaluate(`(async()=>{
    const original=URL.createObjectURL;
    let captured;
    URL.createObjectURL=function(blob){captured=blob;return original.call(URL,blob)};
    try{document.querySelector('[data-export="prediction-json"]').click();
      return JSON.parse(await captured.text())}
    finally{URL.createObjectURL=original}
  })()`);
  return predictionDataSchema.extend({
    coordinate: z.enum(["joint", "cartesian"]), provenance: z.enum(["source", "ik"]),
    channels: z.array(z.object({ channelName: z.string(), unit: z.string() })),
  }).parse(value);
}

